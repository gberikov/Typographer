using Typographer.Rules;

namespace Typographer;

/// <summary>Настройки типографирования HTML-фрагмента.</summary>
public sealed record HtmlOptions
{
    /// <summary>Набор включённых правил. По умолчанию — безопасная типографика.</summary>
    public RuleSet Rules { get; init; } = RuleSet.Default;

    /// <summary>Как выводить типографские символы.</summary>
    public EntityMode Entities { get; init; } = EntityMode.Symbols;

    /// <summary>
    /// Заменять перевод строки тегом переноса.
    /// Опция рассчитана на однократное применение к исходному тексту: повторный прогон
    /// по СОБСТВЕННОМУ ВЫВОДУ типографа (уже содержащему <c>&lt;br /&gt;</c>) вложит теги
    /// повторно и нарушит идемпотентность — гарантия 5 на эту опцию не распространяется.
    /// </summary>
    public bool UseBr { get; init; }

    /// <summary>
    /// Оборачивать абзацы в теги абзаца. Абзацы разделяются пустой строкой и размечаются по
    /// документу целиком, а не по каждому текстовому узлу.
    /// Если во входе уже есть блочная разметка (<c>&lt;p&gt;</c>, <c>&lt;ul&gt;</c>,
    /// <c>&lt;div&gt;</c>…), опция не применяется: границы абзацев в таком документе задаёт
    /// сама разметка. Благодаря этому повторный прогон по собственному выводу типографа
    /// ничего не меняет.
    /// Если пустая строка проходит внутри открытого строчного элемента, обёртка также
    /// пропускается: иначе добавленные теги абзацев пересеклись бы с исходными тегами.
    /// Незакрытая разметка также отключает обёртку, чтобы закрывающий тег абзаца
    /// не попадал внутрь атрибута или защищённого содержимого.
    /// </summary>
    public bool UseP { get; init; }

    /// <summary>
    /// Максимальное число слов, объединяемых в неразрывный блок. Ноль — не объединять.
    /// Опция рассчитана на однократное применение к исходному тексту: повторный прогон
    /// по СОБСТВЕННОМУ ВЫВОДУ типографа (уже содержащему <c>&lt;nobr&gt;</c>) вложит теги
    /// повторно и нарушит идемпотентность — гарантия 5 на эту опцию не распространяется.
    /// </summary>
    public int MaxNobr { get; init; }

    /// <summary>Предел длины результата в символах. Ноль — без ограничения.</summary>
    public int MaxOutputLength { get; init; }

    /// <summary>Настройки по умолчанию.</summary>
    public static HtmlOptions Default { get; } = new();
}
