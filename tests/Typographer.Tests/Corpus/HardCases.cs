        "\n\n\n",
        // Тире прямой речи в начале ВТОРОЙ строки, а не первой.
        "Он вошёл в комнату.\n- Пойдём, - сказал он тихо.",
        // Стек уровней вложенности кавычек не должен разъезжаться или переполняться.
        "\"\"\"\"\"\"\"\"\"\"",
        // Запятая соседствует с другим знаком препинания: запятая-запятая, запятая-точка,
        // запятая-точка с запятой. Между двумя соседними знаками препинания пробела не
        // бывает — правило «пробел после запятой» обязано это учитывать.
        "раз,,два и три,.четыре и пять,;шесть",
        // Запятая перед многоточием: три точки схлопываются в один символ ДО того, как
        // правило пробела после запятой успевает его увидеть — предикат знаков препинания
        // обязан узнавать уже готовое многоточие, а не только сырые точки.
        "раз,...два",
        // Пробел, дописанный правилом «пробел после запятой» прямо в буфер, обязан быть
        // виден правилу тире: иначе тире ставится только со второго прогона.
        "Он сказал,- пойдём",
        // Две группы точек, ставшие соседями только в буфере после удаления пробела перед
        // знаком препинания: многоточие обязано схлопнуться на первом же прогоне.
        "текст. ..",
        "конец. .. Начало",
        // Кавычка сразу за запятой: открывающая, потому что слева в буфере уже стоит пробел,
        // дописанный правилом «пробел после запятой».
        "он сказал,\"да\"",
        // Кавычки вокруг ссылки: тег между ними не должен обнулять стек уровней кавычек.
        "\"<a href=\"#\">Ссылка</a>\"",
        // Тег в начале предложения не должен выглядеть для правил как начало строки.
        "<b>А</b>- б",
        // Закрывающая кавычка сразу за запятой: дописанный перед ней пробел сделал бы её
        // открывающей, и уровни кавычек разъехались бы до конца документа.
