using Typographer.Internal;

namespace Typographer.Tests.Corpus;

/// <summary>Входы, на которых типографы обычно ломаются. Источник — раздел 9 спецификации.</summary>
/// <remarks>
/// Неразрывный пробел и метка порядка байт (BOM) невидимы и неотличимы от соседних символов
/// глазами, поэтому строятся из кода (<see cref="Chars.Nbsp"/>, <c>(char)0xFEFF</c>), а не
/// вставляются как литеральные символы в исходник — инструменты записи файлов уже не раз
/// молча теряли или подменяли такие символы.
/// </remarks>
public static class HardCases
{
    /// <summary>Метка порядка байт (U+FEFF), которая иногда попадает в начало текста из файла.</summary>
    private const char Bom = (char)0xFEFF;

    public static TheoryData<string> All =>
    [
        "Эксперт уточнил: \"в перечень включен закон \"О стандартизации\"\"",
        "17\" и 3' 25\" и диагональ 15,6\"",
        "д'Артаньян, O'Neil, Кот-д'Ивуар",
        "из-за, по-русски, -5 °C, от -5 до +5",
        "- Привет, - сказал он. 1941-1945",
        "3.14 и 1.2.3 и 192.168.0.1 и 01.01.2020",
        "А.С. Пушкин, в 3 г. IV в. до н. э., ул. Ленина, д. 5, кв. 7",
        "10 км/ч, 100 %, 25 °C, № 5, § 3",
        "вот?.. и вот!.. и смайл :-)",
        "<code>a - b</code> и <a title=\"Не трогать - тире\">x</a>",
        "<b>сло</b>во и \"<a href=\"#\">Ссылка</a>\"",
        "<!--[if IE]>только тут<![endif]-->",
        "http://example.com/a-b?x=1&y=2 и user@example.com",
        "$<b>100</b> и 5<sup>2</sup> м",
        "Windows 10 - \"лучшая\" ОС",
        Bom + "текст с BOM",
        "текст с уже" + Chars.Nbsp + "стоящим nbsp",
        "",
        " ",
        "\n\n\n",
        // Тире прямой речи в начале ВТОРОЙ строки, а не первой.
        "Он вошёл в комнату.\n- Пойдём, - сказал он тихо.",
        // Стек уровней вложенности кавычек не должен разъезжаться или переполняться.
        "\"\"\"\"\"\"\"\"\"\"",
        // Запятая соседствует с другим знаком препинания: запятая-запятая, запятая-точка,
        // запятая-точка с запятой. Между двумя соседними знаками препинания пробела не
        // бывает — правило «пробел после запятой» обязано это учитывать.
        "раз,,два и три,.четыре и пять,;шесть",
        // Запятая перед многоточием: три точки схлопываются в один символ ДО того, как
        // правило пробела после запятой успевает его увидеть — предикат знаков препинания
        // обязан узнавать уже готовое многоточие, а не только сырые точки.
        "раз,...два",
        // Пробел, дописанный правилом «пробел после запятой» прямо в буфер, обязан быть
        // виден правилу тире: иначе тире ставится только со второго прогона.
        "Он сказал,- пойдём",
        // Две группы точек, ставшие соседями только в буфере после удаления пробела перед
        // знаком препинания: многоточие обязано схлопнуться на первом же прогоне.
        "текст. ..",
        "конец. .. Начало",
        // Кавычка сразу за запятой: открывающая, потому что слева в буфере уже стоит пробел,
        // дописанный правилом «пробел после запятой».
        "он сказал,\"да\"",
        // Кавычки вокруг ссылки: тег между ними не должен обнулять стек уровней кавычек.
        "\"<a href=\"#\">Ссылка</a>\"",
        // Тег в начале предложения не должен выглядеть для правил как начало строки.
        "<b>А</b>- б",
        // Закрывающая кавычка сразу за запятой: дописанный перед ней пробел сделал бы её
        // открывающей, и уровни кавычек разъехались бы до конца документа.
        "\"Да,\" сказал он. \"Второй\"",
        // Блочный тег — граница строки, даже когда перевода строки между тегами нет.
        "<p>Первый.</p><p>\"Цитата\"</p><p>- Привет</p>",
        "Привет<br />- Пока",
        // Цифры с дефисом, которые диапазоном годов не являются.
        "+7-999-123-45-67 и 01-01-2020 и http://example.com/2024-01-15/post",
        // Пользовательский элемент, имя которого начинается с имени защищённого тега.
        "<code-block>a - b</code-block> \"а\" - б",
        // Ёлочки, уже стоящие во входе, и кавычка после табуляции.
        "«закон \"О стандартизации\"»",
        "\t\"цитата\"",
        // Типографский символ, записанный сущностью: для правил это тот же символ.
        "слово&nbsp;- слово",
        // Закрывающий тег, стоящий там, где он зону не закрывает: в комментарии, в значении
        // атрибута и у вложенного одноимённого элемента.
        "<pre><!-- </pre> -->a - b</pre>",
        "<pre><a title=\"</pre>\">x</a> a - b</pre>",
        "<code>outer <code>inner</code> a - b</code>",
        // Внутри CDATA угловая скобка — обычный символ.
        "<![CDATA[ x > a - b ]]> конец",
        // Инициал на границе, за которой пробела нет.
        "Пушкин А.",
        "Пушкин А., автор",
        // Дефис перед числом с лишним пробелом.
        "текст -  5",
    ];
}
