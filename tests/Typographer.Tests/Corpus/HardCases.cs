using Typographer.Internal;

namespace Typographer.Tests.Corpus;

/// <summary>Входы, на которых типографы обычно ломаются. Источник — раздел 9 спецификации.</summary>
/// <remarks>
/// Неразрывный пробел и метка порядка байт (BOM) невидимы и неотличимы от соседних символов
/// глазами, поэтому строятся из кода (<see cref="Chars.Nbsp"/>, <c>(char)0xFEFF</c>), а не
/// вставляются как литеральные символы в исходник — инструменты записи файлов уже не раз
/// молча теряли или подменяли такие символы.
/// </remarks>
public static class HardCases
{
    /// <summary>Метка порядка байт (U+FEFF), которая иногда попадает в начало текста из файла.</summary>
    private const char Bom = (char)0xFEFF;

    public static TheoryData<string> All =>
